let isMobileMenuOpen = false;

function setMobileMenu(open) {
  isMobileMenuOpen = open;
  if (!mobileMenu) return;

  if (open) {
    mobileMenu.style.transform = "translateX(0)";
    mobileMenu.style.opacity = "1";
    mobileMenu.style.pointerEvents = "auto";
    if (mobileBackdrop) {
      mobileBackdrop.style.opacity = "1";
      mobileBackdrop.style.pointerEvents = "auto";
    }
    if (hamTop) hamTop.style.transform = "translateY(7.8px) rotate(45deg)";
    if (hamMid) {
      hamMid.style.opacity = "0";
      hamMid.style.transform = "translateX(8px)";
    }
    if (hamBot) hamBot.style.transform = "translateY(-7.8px) rotate(-45deg)";
  } else {
    mobileMenu.style.transform = "translateX(120%)";
    mobileMenu.style.opacity = "0";
    mobileMenu.style.pointerEvents = "none";
    if (mobileBackdrop) {
      mobileBackdrop.style.opacity = "0";
      mobileBackdrop.style.pointerEvents = "none";
    }
    if (hamTop) hamTop.style.transform = "none";
    if (hamMid) {
      hamMid.style.opacity = "1";
      hamMid.style.transform = "none";
    }
    if (hamBot) hamBot.style.transform = "none";
  }
}

mobileMenuBtn?.addEventListener("click", (e) => {
  e.stopPropagation();
  setMobileMenu(!isMobileMenuOpen);
});

mobileBackdrop?.addEventListener("click", () => setMobileMenu(false));
document.querySelectorAll(".mobile-link").forEach(link => {
  link.addEventListener("click", () => setMobileMenu(false));
});

