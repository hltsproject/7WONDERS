// Search with Morph Animation
const openSearchBtn = document.getElementById("openSearchBtn");
const searchModal = document.getElementById("searchModal");
const searchBox = document.getElementById("searchBox");
const searchInput = document.getElementById("searchInput");
const searchResults = document.getElementById("searchResults");
const closeSearchBtn = document.getElementById("closeSearchBtn");

if (openSearchBtn) {
  openSearchBtn.style.transition = "transform 0.25s cubic-bezier(0.16, 1, 0.3, 1), color 0.25s ease";
  openSearchBtn.addEventListener("mouseenter", () => (openSearchBtn.style.transform = "scale(1.15)"));
  openSearchBtn.addEventListener("mouseleave", () => (openSearchBtn.style.transform = "scale(1)"));
}

function openSearchModal() {
  if (!searchModal || !searchBox) return;
  if (isMobileMenuOpen) setMobileMenu(false);

  searchModal.classList.remove("hidden");
  searchModal.style.opacity = "0";
  searchModal.style.transition = "opacity 0.3s ease";

  if (openSearchBtn) {
    const btnRect = openSearchBtn.getBoundingClientRect();
    const boxRect = searchBox.getBoundingClientRect();
    const originX = btnRect.left + btnRect.width / 2 - boxRect.left;
    const originY = btnRect.top + btnRect.height / 2 - boxRect.top;
    searchBox.style.transformOrigin = `${originX}px ${originY}px`;
  }

  searchBox.style.opacity = "0";
  searchBox.style.transform = "scale(0.15)";
  searchBox.style.transition = "transform 0.38s cubic-bezier(0.16, 1, 0.3, 1), opacity 0.25s ease";

  requestAnimationFrame(() => {
    requestAnimationFrame(() => {
      searchModal.style.opacity = "1";
      searchBox.style.opacity = "1";
      searchBox.style.transform = "scale(1)";
    });
  });

  setTimeout(() => searchInput?.focus(), 180);
}

function closeSearchModal() {
  if (!searchModal || !searchBox || searchModal.classList.contains("hidden")) return;

  searchModal.style.opacity = "0";
  searchBox.style.opacity = "0";
  searchBox.style.transform = "scale(0.15)";

  setTimeout(() => {
    searchModal.classList.add("hidden");
  }, 320);
}

openSearchBtn?.addEventListener("click", openSearchModal);
closeSearchBtn?.addEventListener("click", closeSearchModal);
searchModal?.addEventListener("click", (e) => {
  if (e.target === searchModal) closeSearchModal();
});
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") {
    closeSearchModal();
    if (isMobileMenuOpen) setMobileMenu(false);
  }
});

searchInput?.addEventListener("input", (e) => {
  const q = e.target.value.toLowerCase().trim();
  if (!q) {
    searchResults.innerHTML = "";
    return;
  }
  const matches = wondersData
    .map((w, idx) => ({ ...w, idx }))
    .filter(w =>
      w.name.toLowerCase().includes(q) ||
      w.location.en.toLowerCase().includes(q) ||
      w.location.id.toLowerCase().includes(q)
    );

  searchResults.innerHTML = matches.length
    ? matches.map(w => `
        <button onclick="closeSearchModal(); openWonderModal(${w.idx})" class="w-full text-left p-3 rounded-xl bg-dark-bg hover:border-gold/40 border border-white/5 flex items-center justify-between cursor-pointer transition-colors">
          <div>
            <p class="font-serif text-lg text-cream">${w.name}</p>
            <p class="text-xs text-muted">${w.location[currentLang]}</p>
          </div>
          <span class="text-xs text-gold">${w.year}</span>
        </button>
      `).join("")
    : `<p class="text-xs text-muted py-2">${translations[currentLang]["search.empty"]}</p>`;
});

