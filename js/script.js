// Language Switcher
const langToggle = document.getElementById("langToggle");
const langDropdown = document.getElementById("langDropdown");
const langText = document.getElementById("langText");
const langOptions = document.querySelectorAll(".lang-option");

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("7wonders_lang", lang);
  document.documentElement.lang = lang;

  if (langText) langText.textContent = lang.toUpperCase();

  langOptions.forEach(opt => {
    const isSelected = opt.dataset.lang === lang;
    opt.classList.toggle("text-gold", isSelected);
    opt.classList.toggle("bg-white/15", isSelected);
    opt.classList.toggle("text-cream/90", !isSelected);
  });

  const dict = translations[lang] || translations.en;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key]) el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.setAttribute("placeholder", dict[key]);
  });

  const activeWonder = wondersData[activeMapIndex];
  const mapLocEl = document.getElementById("mapCurrentLoc");
  if (activeWonder && mapLocEl) {
    mapLocEl.textContent = activeWonder.location[lang];
  }
}

langToggle?.addEventListener("click", (e) => {
  e.stopPropagation();
  langDropdown?.classList.toggle("hidden");
});

langOptions.forEach(opt => {
  opt.addEventListener("click", () => {
    applyLanguage(opt.dataset.lang);
    langDropdown?.classList.add("hidden");
  });
});

document.addEventListener("click", (e) => {
  if (!document.getElementById("langWrapper")?.contains(e.target)) {
    langDropdown?.classList.add("hidden");
  }
});

